check(a.formatJson('{"a":[1,true,null]}',2).value==='\u007b\n  "a": [\n    1,\n    true,\n    null\n  ]\n}','A nested output uses two spaces');
check(a.formatJson('{"a":1}',4).value==='\u007b\n    "a": 1\n}','A four-space formatting');
check(a.formatJson('null',2).value==='null','A null supported');
check(a.formatJson('"资料"',2).value==='"资料"','A JSON string supported');
check(a.formatJson('123',2).value==='123','A JSON number supported');
