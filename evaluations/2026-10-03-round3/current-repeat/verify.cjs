'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
let checks=0;
function check(condition,label) { assert.ok(condition,label); checks++; }
function loadLogic(filename,names) {
  const html=fs.readFileSync(path.join(__dirname,filename),'utf8');
  const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)];
  check(scripts.length===1,filename+' contains one script');
  for(const script of scripts)new vm.Script(script[1],{filename});
  checks++;
  const pure=html.match(/\/\/ PURE_START([\s\S]*?)\/\/ PURE_END/)[1];
  const context=vm.createContext({Date,Set,Number,String,JSON,Math,Error});
  vm.runInContext(pure+'\nglobalThis.api={'+names.join(',')+'};',context);
  return context.api;
}
